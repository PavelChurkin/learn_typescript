/**
 * Модуль 01: Введение в TypeScript и базовые типы данных
 *
 * TypeScript - это надмножество JavaScript, которое добавляет статическую типизацию.
 * Это помогает обнаруживать ошибки на этапе разработки, а не во время выполнения.
 */

console.log('=== Модуль 01: Введение в TypeScript ===\n');

// ============================================
// 1. БАЗОВЫЕ ТИПЫ ДАННЫХ
// ============================================

console.log('1. БАЗОВЫЕ ТИПЫ ДАННЫХ\n');

// Number - числовой тип данных (целые числа и числа с плавающей точкой)
const age: number = 25;
const price: number = 19.99;
const negative: number = -10;
console.log(`Возраст: ${age}, Цена: ${price}, Отрицательное число: ${negative}`);

// String - строковый тип данных
const name: string = 'Иван';
const greeting: string = "Привет, мир!"; // можно использовать одинарные или двойные кавычки
const template: string = `Привет, ${name}!`; // шаблонные строки с интерполяцией
console.log(`Имя: ${name}, Приветствие: ${greeting}, Шаблон: ${template}`);

// Boolean - логический тип данных (true или false)
const isActive: boolean = true;
const isCompleted: boolean = false;
console.log(`Активен: ${isActive}, Завершено: ${isCompleted}`);

// Null и Undefined - специальные типы
let emptyValue: null = null; // явное отсутствие значения
let notDefined: undefined = undefined; // переменная объявлена, но не инициализирована
console.log(`Пустое значение: ${emptyValue}, Не определено: ${notDefined}`);

// ============================================
// 2. РАСШИРЕННЫЕ ТИПЫ
// ============================================

console.log('\n2. РАСШИРЕННЫЕ ТИПЫ\n');

// Any - любой тип (использовать с осторожностью, теряется проверка типов)
let dynamicValue: any = 42;
dynamicValue = 'строка'; // можно присвоить любой тип
dynamicValue = true;
console.log(`Динамическое значение: ${dynamicValue}`);

// Unknown - безопасная альтернатива any (требует проверки типа перед использованием)
let unknownValue: unknown = 10;
// unknownValue.toFixed(); // ошибка компиляции
if (typeof unknownValue === 'number') {
  console.log(`Unknown как число: ${unknownValue.toFixed(2)}`);
}

// Void - отсутствие возвращаемого значения (обычно для функций)
function logMessage(message: string): void {
  console.log(`Лог: ${message}`);
  // функция ничего не возвращает
}
logMessage('Это сообщение из функции void');

// Never - тип для функций, которые никогда не возвращают управление
function throwError(message: string): never {
  throw new Error(message);
}
// throwError('Пример ошибки'); // раскомментируйте, чтобы увидеть ошибку

// ============================================
// 3. ЛИТЕРАЛЬНЫЕ ТИПЫ
// ============================================

console.log('\n3. ЛИТЕРАЛЬНЫЕ ТИПЫ\n');

// Литеральный тип - переменная может иметь только конкретное значение
let direction: 'left' | 'right' | 'up' | 'down';
direction = 'left'; // OK
// direction = 'forward'; // ошибка компиляции
console.log(`Направление: ${direction}`);

// Числовые литералы
let diceRoll: 1 | 2 | 3 | 4 | 5 | 6;
diceRoll = 4;
console.log(`Бросок кубика: ${diceRoll}`);

// ============================================
// 4. ТИПЫ-ОБЪЕДИНЕНИЯ И ПЕРЕСЕЧЕНИЯ
// ============================================

console.log('\n4. ТИПЫ-ОБЪЕДИНЕНИЯ И ПЕРЕСЕЧЕНИЯ\n');

// Union (объединение) - переменная может быть одним из нескольких типов
let mixedValue: string | number;
mixedValue = 'текст'; // OK
console.log(`Смешанное значение (строка): ${mixedValue}`);
mixedValue = 100; // OK
console.log(`Смешанное значение (число): ${mixedValue}`);

// Type alias (псевдоним типа) - создание собственных именованных типов
type ID = string | number;
let userId: ID = 'user_123';
let productId: ID = 456;
console.log(`ID пользователя: ${userId}, ID продукта: ${productId}`);

// ============================================
// 5. TYPE ASSERTION (УТВЕРЖДЕНИЕ ТИПА)
// ============================================

console.log('\n5. УТВЕРЖДЕНИЕ ТИПА\n');

// Когда вы знаете больше о типе, чем TypeScript
let someValue: unknown = 'это строка';
let strLength: number = (someValue as string).length; // утверждение типа с помощью as
console.log(`Длина строки: ${strLength}`);

// Альтернативный синтаксис (не работает в JSX)
let anotherValue: unknown = 'другая строка';
let anotherLength: number = (<string>anotherValue).length;
console.log(`Длина другой строки: ${anotherLength}`);

// ============================================
// 6. ТИПИЗАЦИЯ КОНСТАНТ
// ============================================

console.log('\n6. ТИПИЗАЦИЯ КОНСТАНТ\n');

// Const создает неизменяемую привязку (ссылку), но не делает значение неизменяемым
const PI: number = 3.14159;
// PI = 3.14; // ошибка: нельзя переназначить константу
console.log(`Число PI: ${PI}`);

// Константы объектов можно изменять (их свойства)
const person = {
  name: 'Мария',
  age: 30
};
person.age = 31; // OK - изменение свойства
// person = {}; // ошибка: нельзя переназначить константу
console.log(`Персона: ${person.name}, возраст: ${person.age}`);

console.log('\n=== Модуль 01 завершен ===\n');

/**
 * СОВЕТЫ ПО ПРОИЗВОДИТЕЛЬНОСТИ:
 *
 * 1. Используйте строгую типизацию - это помогает компилятору оптимизировать код
 * 2. Избегайте типа 'any' - он отключает проверку типов и может привести к ошибкам
 * 3. Используйте 'const' для неизменяемых значений - это позволяет движку JS лучше оптимизировать код
 * 4. Используйте 'unknown' вместо 'any' когда тип неизвестен - это безопаснее
 * 5. Литеральные типы помогают предотвратить ошибки и улучшают читаемость кода
 */
